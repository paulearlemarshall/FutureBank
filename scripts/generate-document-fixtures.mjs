import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const fixtures = [
  { slot: "PASSPORT", filename: "Passport-AmeliaHart.jpg" },
  { slot: "NATIONAL_ID", filename: "EmiratesID-AmeliaHart.jpg" },
];

const rows = [];
for (const fixture of fixtures) {
  const content = await readFile(path.join(root, "TestDocs", fixture.filename));
  rows.push({ ...fixture, mimeType: "image/jpeg", sizeBytes: content.byteLength, sha256: createHash("sha256").update(content).digest("hex"), base64: content.toString("base64") });
}

const source = `// Generated by scripts/generate-document-fixtures.mjs. Do not edit by hand.\nexport const seededCustomerDocuments = ${JSON.stringify(rows, null, 2)} as const;\n`;
await writeFile(path.join(root, "src", "db", "seed-document-fixtures.generated.ts"), source, "utf8");
